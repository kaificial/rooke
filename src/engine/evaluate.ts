const TABLES: Readonly<Record<PieceType, readonly number[]>> = {
  p: PAWN,
  n: KNIGHT,
  b: BISHOP,
  r: ROOK,
  q: QUEEN,
  k: KING,
}

/** Static evaluation in centipawns, positive when white is better. */
export function evaluate(pos: Position): number {
  let score = 0
  for (let sq = 0; sq < 64; sq++) {
    const piece = pos.board[sq]
    if (!piece) continue
    const table = TABLES[piece.type]
    if (piece.color === 'w') {
      score += PIECE_VALUES[piece.type] + table[sq]
    } else {
      // Black reads the table flipped vertically (a8 <-> a1), i.e. sq ^ 56.
      score -= PIECE_VALUES[piece.type] + table[sq ^ 56]
    }
  }
  return score
}
